/// The user picked a dataset blueprint that the viewer is still streaming. The button and the
/// open dropdown show the picked blueprint with a loading indicator, and the picked blueprint has
/// no actions menu yet.
#[test]
fn dataset_blueprint_dropdown_shows_loading_pick() {
    let test_context = TestContext::new();
    let dataset_blueprints = test_dataset_blueprints();
    activate_clone_of(
        &test_context,
        &blueprint_store_id(&test_context, DEFAULT_SEGMENT),
    );
    let loading_id = blueprint_store_id(&test_context, OTHER_SEGMENT);

    let mut harness = build_dropdown_harness(&test_context, &dataset_blueprints, Some(&loading_id));
    step_until(
        "the button shows the picked blueprint",
        &mut harness,
        |harness| harness.query_by_label(OTHER_NAME).is_some(),
    );
    harness.get_by_label("Loading the picked blueprint");

    harness.get_by_label(OTHER_NAME).click();
    step_until("the dropdown is open", &mut harness, |harness| {
        harness.query_by_label("Heuristic").is_some()
    });
    assert_eq!(
        harness
            .query_all_by_label("Loading the picked blueprint")
            .count(),
        2,
        "the button and the row of the picked blueprint should show a loading indicator"
    );
    assert!(
        harness.query_by_label("Actions").is_none(),
        "a blueprint that is still loading should have no actions menu"
    );
    harness.snapshot("dataset_blueprint_dropdown_loading");
}

/// The server is listing the blueprints of the dataset again. The open dropdown shows the
/// blueprints it listed before, and a loading indicator next to its heading.
#[test]
fn dataset_blueprint_dropdown_listing_again() {
    let test_context = TestContext::new();
    let listed = test_dataset_blueprints();
    let dataset_blueprints = DatasetBlueprints {
        blueprints: ServerValue::Pending {
            previous: listed.blueprints.get().cloned(),
        },
        ..listed
    };
    activate_clone_of(
        &test_context,
        &blueprint_store_id(&test_context, OTHER_SEGMENT),
    );

    let mut harness = build_dropdown_harness(&test_context, &dataset_blueprints, None);
    step_until("the button is shown", &mut harness, |harness| {
        harness.query_by_label(OTHER_NAME).is_some()
    });
    harness.get_by_label(OTHER_NAME).click();
    step_until("the dropdown is open", &mut harness, |harness| {
        harness.query_by_label("Heuristic").is_some()
    });
    harness.get_by_label("Loading the blueprints registered for this dataset");
    harness.snapshot("dataset_blueprint_dropdown_listing_again");
}

/// The server could not list the blueprints of the dataset.
/// The open dropdown shows the error.
#[test]
fn dataset_blueprint_dropdown_listing_failed() {
    let test_context = TestContext::new();
    let origin = re_uri::Origin::test();
    let dataset_blueprints = DatasetBlueprints {
        blueprints: ServerValue::Unavailable {
            previous: None,
            err: re_redap_client::ApiError::connection(&origin, "Failed to list the blueprints"),
        },
        ..test_dataset_blueprints()
    };

    let mut harness = dropdown_harness(&test_context, &dataset_blueprints);
    harness.get_by_label("Custom").click();
    harness.run();

    assert!(
        harness
            .query_by_label("Loading the blueprints registered for this dataset")
            .is_none(),
        "the dropdown should not show the loading indicator"
    );
    harness.get_by_label_contains("Failed to list the blueprints");
    harness.snapshot("dataset_blueprint_dropdown_listing_failed");
}

