fn test_dataset_blueprints() -> DatasetBlueprints {
    DatasetBlueprints {
        origin: re_uri::Origin::test(),
        blueprint_dataset: EntryId::new(),
        blueprints: ServerValue::Completed(Arc::new(vec![
            recording_blueprint(DEFAULT_SEGMENT, Some(DEFAULT_NAME)),
            recording_blueprint(OTHER_SEGMENT, Some(OTHER_NAME)),
            recording_blueprint(UNNAMED_SEGMENT, None),
        ])),
        default_segment: Some(SegmentId::from(DEFAULT_SEGMENT)),
    }
}

fn recording_blueprint(segment: &str, name: Option<&str>) -> RegisteredBlueprint {
    RegisteredBlueprint {
        segment_id: SegmentId::from(segment),
        name: name.map(|name| BlueprintName::try_new(name).expect("non-empty name")),
        kind: Some(BlueprintKind::Recording),
        registration_time: None,
    }
}

/// The store id of the dataset blueprint in `segment` once it is streamed for the test application.
fn blueprint_store_id(test_context: &TestContext, segment: &str) -> StoreId {
    re_redap_client::blueprint_store_id_for_segment(
        test_context.application_id.clone(),
        &SegmentId::from(segment),
    )
}

/// Adds an empty blueprint store with `source_id`, streamed from a catalog server the way a
/// dataset blueprint is, and activates a clone of it.
fn activate_clone_of(test_context: &TestContext, source_id: &StoreId) {
    let mut store_hub = test_context.store_hub.lock();
    let mut source = EntityDb::new(source_id.clone());
    source.add_data_source(&Arc::new(LogSource::RedapGrpcStream {
        uri: re_uri::DatasetUri {
            origin: re_uri::Origin::test(),
            dataset_id: EntryId::new().id,
            resource: re_uri::DatasetResource::Segments,
            segment_id: Some(SegmentId::from(source_id.recording_id())),
            fragment: Default::default(),
        },
        open_behavior: re_log_channel::RecordingOpenBehavior::Background,
    }));
    store_hub.insert_entity_db(source);
    store_hub
        .set_cloned_blueprint_active_for_app(source_id)
        .expect("the source blueprint is in the hub");
}

/// Activates an empty blueprint store with `blueprint_id` as is, without cloning it.
fn activate_without_source(test_context: &TestContext, blueprint_id: StoreId) {
    let mut bundle = StoreBundle::default();
    bundle.insert(EntityDb::new(blueprint_id));
    test_context
        .store_hub
        .lock()
        .load_blueprint_store(bundle, &test_context.application_id)
        .expect("the blueprint belongs to the test application");
}

/// The dropdown sits at the right end of a row, like in the top panel.
///
/// Runs the harness before returning it.
fn dropdown_harness<'a>(
    test_context: &'a TestContext,
    dataset_blueprints: &'a DatasetBlueprints,
) -> egui_kittest::Harness<'a> {
    let mut harness = build_dropdown_harness(test_context, dataset_blueprints, None);
    harness.run();
    harness
}

/// Like [`dropdown_harness`], with `loading_blueprint` as the picked blueprint that the viewer is
/// still streaming. Doesn't run the harness.
fn build_dropdown_harness<'a>(
    test_context: &'a TestContext,
    dataset_blueprints: &'a DatasetBlueprints,
    loading_blueprint: Option<&'a StoreId>,
) -> egui_kittest::Harness<'a> {
    test_context
        .setup_kittest_for_rendering_ui([600.0, 300.0])
        .build_ui(move |ui| {
            ui.set_min_size(ui.available_size());
            test_context.run(&ui.ctx().clone(), |viewer_ctx| {
                ui.with_layout(egui::Layout::right_to_left(egui::Align::Min), |ui| {
                    dataset_blueprint_dropdown_ui(
                        ui,
                        viewer_ctx.store_context,
                        viewer_ctx.store_hub(),
                        viewer_ctx.command_sender(),
                        dataset_blueprints,
                        loading_blueprint,
                    );
                });
            });

            test_context.handle_system_commands(ui.ctx());
        })
}

/// Opens the dropdown with the button that shows `active_name`, then the actions menu of the
/// active blueprint.
fn open_actions_menu(harness: &mut egui_kittest::Harness<'_>, active_name: &str) {
    harness.get_by_label(active_name).click();
    harness.run();
    harness.get_by_label("Actions").click();
    harness.run();
}

fn assert_dropdown_label(harness: &egui_kittest::Harness<'_>, label: &str) {
    assert!(
        harness.query_by_label(label).is_some(),
        "the blueprint dropdown should show {label:?}"
    );
}
