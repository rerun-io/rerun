/// The active blueprint is a copy of a dataset blueprint that isn't in the dataset's list of
/// blueprints. The dropdown shows a fixed label.
#[test]
fn dataset_blueprint_dropdown_source_not_in_dataset() {
    let test_context = TestContext::new();
    let dataset_blueprints = test_dataset_blueprints();
    activate_clone_of(
        &test_context,
        &blueprint_store_id(&test_context, UNLISTED_SEGMENT),
    );
    {
        let store_hub = test_context.store_hub.lock();
        let active_id = store_hub
            .active_blueprint_id_for_app(&test_context.application_id)
            .expect("a blueprint is active");
        assert_eq!(
            store_hub.copied_dataset_blueprint(active_id),
            Some(SegmentId::from(UNLISTED_SEGMENT)),
            "the active blueprint should be a copy of the unlisted dataset blueprint"
        );
    }

    let harness = dropdown_harness(&test_context, &dataset_blueprints);
    assert_dropdown_label(&harness, "Custom");
}

