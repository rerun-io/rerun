const DEFAULT_SEGMENT: &str = "overview_segment";
const DEFAULT_NAME: &str = "Overview of every camera and every sensor";
const OTHER_SEGMENT: &str = "detail_segment";
const OTHER_NAME: &str = "Detail";
const UNNAMED_SEGMENT: &str = "unnamed_segment";
const UNLISTED_SEGMENT: &str = "unlisted_segment";

/// The dataset has a blueprint the user picked, and a different default blueprint.
/// The dropdown shows the name of the picked blueprint, and its list marks the default one.
#[test]
fn dataset_blueprint_dropdown_shows_default_marker() {
    let test_context = TestContext::new();
    let dataset_blueprints = test_dataset_blueprints();
    activate_clone_of(
        &test_context,
        &blueprint_store_id(&test_context, OTHER_SEGMENT),
    );

    let mut harness = dropdown_harness(&test_context, &dataset_blueprints);
    assert_dropdown_label(&harness, OTHER_NAME);

    harness.get_by_label(OTHER_NAME).click();
    harness.run();
    harness.snapshot("dataset_blueprint_dropdown_open");
}

/// The active blueprint has a menu with the actions for it, which opens on top of the dropdown in
/// the dark and the light theme. Picking an action closes the menu and the dropdown.
#[test]
fn dataset_blueprint_dropdown_actions_menu() {
    let test_context = TestContext::new();
    let dataset_blueprints = test_dataset_blueprints();
    activate_clone_of(
        &test_context,
        &blueprint_store_id(&test_context, OTHER_SEGMENT),
    );

    let mut harness = dropdown_harness(&test_context, &dataset_blueprints);
    open_actions_menu(&mut harness, OTHER_NAME);

    harness.get_by_label("Revert changes");
    harness.get_by_label("Export .rbl…");
    harness.snapshot("dataset_blueprint_dropdown_actions");
    harness.ctx.set_theme(egui::Theme::Light);
    harness.run();
    harness.snapshot("dataset_blueprint_dropdown_actions_light");

    harness.get_by_label("Export .rbl…").click();
    harness.run();
    assert!(
        harness.query_by_label("Export .rbl…").is_none(),
        "picking an action should close the actions menu"
    );
    assert!(
        harness.query_by_label("Heuristic").is_none(),
        "picking an action should close the dropdown"
    );
}

/// The actions menu is open on top of the dropdown, and the user clicks outside both.
/// One click closes both.
#[test]
fn dataset_blueprint_dropdown_click_outside_closes_both() {
    let test_context = TestContext::new();
    let dataset_blueprints = test_dataset_blueprints();
    activate_clone_of(
        &test_context,
        &blueprint_store_id(&test_context, OTHER_SEGMENT),
    );

    let mut harness = dropdown_harness(&test_context, &dataset_blueprints);
    open_actions_menu(&mut harness, OTHER_NAME);

    let outside = egui::pos2(10.0, 280.0);
    harness.hover_at(outside);
    harness.run();
    for pressed in [true, false] {
        harness.event(egui::Event::PointerButton {
            pos: outside,
            button: egui::PointerButton::Primary,
            pressed,
            modifiers: egui::Modifiers::NONE,
        });
        harness.run();
    }

    assert!(
        harness.query_by_label("Export .rbl…").is_none(),
        "the click should close the actions menu"
    );
    assert!(
        harness.query_by_label("Heuristic").is_none(),
        "the click should close the dropdown"
    );
}

