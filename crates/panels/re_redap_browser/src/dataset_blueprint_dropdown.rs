/// The name of the blueprint the viewer generates with its heuristics.
const HEURISTIC_BLUEPRINT_NAME: &str = "Heuristic";

/// The name of an active blueprint that is neither generated by the heuristics nor a clone of one
/// of the dataset's blueprints.
const CUSTOM_BLUEPRINT_NAME: &str = "Custom";

/// The label of a dataset blueprint without a stored name.
const UNNAMED_BLUEPRINT_LABEL: &str = "<unnamed>";

/// The widest the dropdown button gets before its label is truncated.
const BUTTON_MAX_WIDTH: f32 = 175.0;

/// The width of the open dropdown. Longer blueprint names are truncated.
const POPUP_WIDTH: f32 = 218.0;

/// The gap between the open dropdown and the button that opened it, and between the open
/// dropdown and the actions menu.
const POPUP_GAP: f32 = 3.0;

/// The gap between the edges of the open dropdown and its rows.
const POPUP_PADDING: i8 = 6;

/// The height of a row in the open dropdown.
const ROW_HEIGHT: f32 = 32.0;

/// The gap between the edges of a row and its content.
const ROW_PADDING: i8 = 10;

/// The gap between the right edge of the active row and its actions button.
const ACTIVE_ROW_RIGHT_PADDING: i8 = 6;

/// The gap above the heading of the open dropdown.
const HEADING_PADDING_TOP: i8 = 8;

/// The gap below the heading of the open dropdown.
const HEADING_PADDING_BOTTOM: i8 = 4;

/// The gap between the parts of a row.
const ICON_GAP: f32 = 10.0;

/// The label of the row that asks the agent to create a blueprint.
const CREATE_WITH_AGENT_LABEL: &str = "Create with agent";

/// What the row labeled [`CREATE_WITH_AGENT_LABEL`] asks the agent.
const CREATE_WITH_AGENT_PROMPT: &str = "Create a blueprint for this recording";

/// The size of the star after the name of the default blueprint.
const STAR_SIZE: f32 = 12.0;

/// A dropdown to switch between the heuristic blueprint and the blueprints of the recording's
/// dataset.
///
/// The active blueprint has a menu to export it to a file, or to revert its changes.
///
/// `loading_blueprint` is the dataset blueprint the user picked that the viewer is still
/// streaming. Until it becomes active, the dropdown shows it in place of the active blueprint,
/// with a loading indicator in place of its icon.
///
/// Returns true in the frame the user opens the dropdown.
pub fn dataset_blueprint_dropdown_ui(
    ui: &mut egui::Ui,
    store_context: &ActiveStoreContext<'_>,
    store_hub: &StoreHub,
    command_sender: &CommandSender,
    dataset_blueprints: &DatasetBlueprints,
    loading_blueprint: Option<&StoreId>,
) -> bool {
    let application_id = store_context.application_id();
    let active_blueprint = store_context.blueprint;
    let heuristic_id = StoreId::heuristic_blueprint(application_id.clone());
    let is_loading = loading_blueprint.is_some();
    let is_heuristic = !is_loading && *active_blueprint.store_id() == heuristic_id;

    let copied_segment = store_hub.copied_dataset_blueprint(active_blueprint.store_id());
    let active = copied_segment.as_ref().and_then(|segment| {
        dataset_blueprints
            .recording_blueprints()?
            .find(|blueprint| &blueprint.segment_id == segment)
    });
    let loading = loading_blueprint.and_then(|loading_id| {
        dataset_blueprints
            .recording_blueprints()?
            .find(|blueprint| {
                re_redap_client::blueprint_store_id_for_segment(
                    application_id.clone(),
                    &blueprint.segment_id,
                ) == *loading_id
            })
    });
    let is_listing_pending = matches!(dataset_blueprints.blueprints, ServerValue::Pending { .. });

    // The blueprint the dropdown shows as picked.
    let shown = loading.or(active);

    let label = if is_heuristic {
        RichText::new(HEURISTIC_BLUEPRINT_NAME)
    } else if let Some(shown) = shown {
        blueprint_name_text(
            ui,
            shown.name.as_ref().map(BlueprintName::as_str),
            |label| RichText::new(label),
        )
    } else if (is_loading || copied_segment.is_some()) && is_listing_pending {
        // The server is still listing the blueprints the shown blueprint may be one of.
        blueprint_name_text(ui, None, |label| RichText::new(label))
    } else {
        RichText::new(CUSTOM_BLUEPRINT_NAME)
    };

    let hover_text = format!(
        "{}\n\nSwitch between the blueprints registered for this dataset",
        label.text()
    );
    let tokens = ui.tokens();
    let icon_id = IdSalt::new("icon");
    let button = egui::Button::new((
        Atom::custom(icon_id, tokens.small_icon_size),
        label,
        &re_ui::icons::DROPDOWN_ARROW,
    ))
    .gap(tokens.text_to_icon_padding());
    let response = ui
        .scope(|ui| {
            ui.set_max_width(BUTTON_MAX_WIDTH);
            let button = button.outlined().truncate().atom_ui(ui);
            if let Some(icon_rect) = button.rect(icon_id) {
                paint_blueprint_icon(ui, icon_rect, tokens.list_item_default_icon, is_loading);
            }
            button.response
        })
        .inner
        .on_hover_text(hover_text);

    // The dropdown keeps its own open state, so the actions menu can open on top of it.
    // TODO(emilk/egui#7451): let egui handle that when popup-in-popup is supported.
    let popup_id = response.id.with("blueprints");
    let mut popup_open: bool = ui.data(|data| data.get_temp(popup_id)).unwrap_or_default();
    let opened_this_frame = response.clicked() && !popup_open;
    if response.clicked() {
        popup_open = !popup_open;
    }

    let actions = BlueprintActions {
        store_context,
        revert_disabled_reason: reset_blueprint_disabled_reason(
            active_blueprint,
            store_hub.store_bundle(),
        ),
        command_sender,
        menu_id: popup_id.with("actions"),
        sent_command: Cell::new(false),
    };

    // A click in the actions menu is outside the dropdown, and leaves the dropdown open.
    let pointer_in_actions_menu = ui
        .ctx()
        .pointer_interact_pos()
        .and_then(|pos| ui.ctx().layer_id_at(pos))
        .is_some_and(|layer| layer.id == actions.menu_id);
    let close_behavior = if pointer_in_actions_menu {
        PopupCloseBehavior::IgnoreClicks
    } else {
        PopupCloseBehavior::CloseOnClickOutside
    };

    Popup::menu(&response)
        .id(popup_id)
        .style(StyleModifier::new(|style| {
            menu_style().apply(style);
            style.spacing.menu_margin = Margin::same(POPUP_PADDING);
        }))
        .close_behavior(close_behavior)
        .align(RectAlign::BOTTOM_END)
        .gap(POPUP_GAP)
        .open_bool(&mut popup_open)
        .show(|ui| {
            ui.set_width(POPUP_WIDTH - 2.0 * f32::from(POPUP_PADDING));

            let tokens = ui.tokens();
            let listing_indicator_id = IdSalt::new("listing_indicator");
            let mut heading = Atoms::new(
                tokens
                    .eyebrow_text(ui.style(), "Blueprints")
                    .color(tokens.text_subdued),
            );
            if is_listing_pending {
                heading.push_right(Atom::custom(listing_indicator_id, tokens.small_icon_size));
            }
            let heading = WidgetAtom::new(heading)
                .frame(Frame::new().inner_margin(Margin {
                    left: ROW_PADDING,
                    right: ROW_PADDING,
                    top: HEADING_PADDING_TOP,
                    bottom: HEADING_PADDING_BOTTOM,
                }))
                .gap(tokens.text_to_icon_padding())
                .allocate(ui)
                .paint(ui);
            if let Some(indicator_rect) = heading.rect(listing_indicator_id) {
                paint_loading_indicator(
                    ui,
                    indicator_rect,
                    tokens.text_subdued,
                    "Loading the blueprints registered for this dataset",
                );
            }

            let heuristic_item = BlueprintItem {
                row_id: ui.make_persistent_id("heuristic_blueprint"),
                name: Some(HEURISTIC_BLUEPRINT_NAME),
                is_active: is_heuristic,
                is_loading: false,
                is_default: false,
            };
            if heuristic_item.ui(ui, &actions) {
                command_sender.send_system(SystemCommand::ActivateHeuristicBlueprint(
                    application_id.clone(),
                ));
            }

            let shown_segment = shown.map(|shown| &shown.segment_id);
            dataset_blueprint_items_ui(ui, &actions, dataset_blueprints, shown_segment, is_loading);

            ui.separator();
            create_blueprint_with_agent_row_ui(ui, &actions);

            if actions.sent_command.get() {
                ui.close();
            }
        });

    ui.data_mut(|data| data.insert_temp(popup_id, popup_open));

    opened_this_frame
}

/// Lists the blueprints of the dataset.
///
/// While the server lists the blueprints, shows the blueprints it listed before. If listing them
/// failed, shows the error. Clicking a blueprint other than `shown_segment` makes it the active
/// blueprint.
///
/// If `is_loading`, the viewer is streaming the blueprint of `shown_segment`.
fn dataset_blueprint_items_ui(
    ui: &mut egui::Ui,
    actions: &BlueprintActions<'_, '_>,
    dataset_blueprints: &DatasetBlueprints,
    shown_segment: Option<&SegmentId>,
    is_loading: bool,
) {
    let blueprints = dataset_blueprints.recording_blueprints();
    let listing_err = dataset_blueprints
        .blueprints
        .get_err()
        .filter(|_| blueprints.is_none());

    for blueprint in blueprints.into_iter().flatten() {
        let segment = &blueprint.segment_id;
        let is_shown = shown_segment == Some(segment);
        let item = BlueprintItem {
            row_id: ui.make_persistent_id(("dataset_blueprint", segment)),
            name: blueprint.name.as_ref().map(BlueprintName::as_str),
            is_active: is_shown,
            is_loading: is_shown && is_loading,
            is_default: dataset_blueprints.default_segment.as_ref() == Some(segment),
        };

        if item.ui(ui, actions) {
            actions
                .command_sender
                .send_system(SystemCommand::ActivateDatasetBlueprint {
                    application_id: actions.store_context.application_id().clone(),
                    origin: dataset_blueprints.origin.clone(),
                    blueprint_dataset: dataset_blueprints.blueprint_dataset,
                    blueprint_segment: segment.clone(),
                });
        }
    }

    if let Some(err) = listing_err {
        Frame::new()
            .inner_margin(Margin::symmetric(ROW_PADDING, 0))
            .show(ui, |ui| {
                ui.error_label(err.to_string());
            });
    }
}

/// A row that asks the agent in the agent panel to create a blueprint for the recording.
///
/// Clicking it closes the dropdown.
fn create_blueprint_with_agent_row_ui(ui: &mut egui::Ui, actions: &BlueprintActions<'_, '_>) {
    let tokens = ui.tokens();

    let row = row_widget(
        ui,
        (
            re_ui::icons::AGENT
                .as_image()
                .tint(tokens.list_item_default_icon)
                .atom_size(tokens.small_icon_size),
            RichText::new(CREATE_WITH_AGENT_LABEL).color(tokens.text_default),
            Atom::grow(),
        ),
        ROW_PADDING,
    )
    .allocate(ui);
    let response = paint_row(ui, row, false).response;
    response.widget_info(|| {
        WidgetInfo::labeled(egui::Role::Button, ui.is_enabled(), CREATE_WITH_AGENT_LABEL)
    });
    let response = response.on_hover_text("Ask the agent in the agent panel to create a blueprint");

    if response.clicked() {
        actions
            .command_sender
            .send_system(SystemCommand::TriggerPrompt {
                model: ModelCategory::Fast.into(),
                prompt: CREATE_WITH_AGENT_PROMPT.to_owned(),
            });
        actions.sent_command.set(true);
    }
}

/// A row of the open dropdown, around `atoms`.
///
/// `right_padding` is the gap between the right edge of the row and its content.
fn row_widget<'a>(
    ui: &egui::Ui,
    atoms: impl egui::IntoAtoms<'a>,
    right_padding: i8,
) -> WidgetAtom<'a> {
    WidgetAtom::new(atoms)
        .frame(
            Frame::new()
                .inner_margin(Margin {
                    left: ROW_PADDING,
                    right: right_padding,
                    top: 0,
                    bottom: 0,
                })
                .corner_radius(ui.tokens().normal_corner_radius()),
        )
        .gap(ICON_GAP)
        .min_size(Vec2::new(0.0, ROW_HEIGHT))
        .wrap_mode(TextWrapMode::Truncate)
        .sense(Sense::click())
}

/// Paints a row of the open dropdown, filled when it is the active one or hovered.
fn paint_row(
    ui: &egui::Ui,
    mut row: egui::AllocatedWidgetAtom<'_>,
    is_active: bool,
) -> egui::WidgetAtomResponse {
    let tokens = ui.tokens();
    if is_active {
        row.frame = row.frame.fill(tokens.button_opened.fill);
    } else if row.response.hovered() {
        row.frame = row.frame.fill(tokens.list_item_hovered_bg);
    }
    row.paint(ui)
}

/// The name of a blueprint formatted with `text`.
///
/// A blueprint without a stored name shows [`UNNAMED_BLUEPRINT_LABEL`] in a subdued color.
fn blueprint_name_text(
    ui: &egui::Ui,
    name: Option<&str>,
    text: impl FnOnce(&str) -> RichText,
) -> RichText {
    match name {
        Some(name) => text(name),
        None => text(UNNAMED_BLUEPRINT_LABEL).color(ui.tokens().text_subdued),
    }
}

/// Paints a loading indicator in `rect`, in a child `Ui` that leaves the layout of `ui` as it is.
fn paint_loading_indicator(ui: &mut egui::Ui, rect: Rect, tint: Color32, reason: &str) {
    let mut indicator_ui = ui.new_child(egui::UiBuilder::new().max_rect(rect));
    re_ui::loading_indicator::paint_loading_indicator_inside(
        &mut indicator_ui,
        Align2::CENTER_CENTER,
        rect,
        1.0,
        Some(tint),
        reason,
    );
}

/// Paints the blueprint icon of a row or of the dropdown button, or a loading indicator if
/// `is_loading`.
fn paint_blueprint_icon(ui: &mut egui::Ui, rect: Rect, tint: Color32, is_loading: bool) {
    if is_loading {
        paint_loading_indicator(ui, rect, tint, "Loading the picked blueprint");
    } else {
        re_ui::icons::LAYOUT
            .as_image()
            .tint(tint)
            .paint_at(ui, rect);
    }
}

/// One blueprint in the open dropdown.
struct BlueprintItem<'a> {
    /// The id of the row.
    ///
    /// It only depends on the blueprint, and not on what the dropdown shows above the row.
    row_id: egui::Id,

    /// `None` for a blueprint without a stored name.
    name: Option<&'a str>,

    /// Whether the dropdown shows this blueprint as picked.
    is_active: bool,

    /// Whether the viewer is streaming this blueprint before it becomes active.
    is_loading: bool,

    is_default: bool,
}

impl BlueprintItem<'_> {
    /// Returns `true` if the user picked this blueprint and it isn't the active one.
    ///
    /// Clicking the item closes the dropdown. Only the active blueprint has a menu with its
    /// actions, and only once it has loaded.
    fn ui(&self, ui: &mut egui::Ui, actions: &BlueprintActions<'_, '_>) -> bool {
        let tokens = ui.tokens();
        let icon_id = IdSalt::new("icon");
        let actions_button_id = IdSalt::new("actions_button");
        let has_actions = self.is_active && !self.is_loading;

        let icon_tint = if self.is_active {
            tokens.selection_bg_fill
        } else {
            tokens.list_item_default_icon
        };
        let name = blueprint_name_text(ui, self.name, |label| {
            if self.is_active {
                tokens.body_medium_text(label)
            } else {
                RichText::new(label)
            }
            .color(tokens.text_default)
        });
        let label = name.text().to_owned();

        let mut name_and_star = Atoms::new(name);
        if self.is_default {
            name_and_star.push_right(
                re_ui::icons::STAR
                    .as_image()
                    .tint(tokens.selection_bg_fill)
                    .atom_size(Vec2::splat(STAR_SIZE)),
            );
        }

        let mut atoms = Atoms::new((
            Atom::custom(icon_id, tokens.small_icon_size),
            ContainerAtom::new(name_and_star)
                .gap(tokens.text_to_icon_padding())
                .wrap_mode(TextWrapMode::Truncate)
                .atom_shrink(true),
            Atom::grow(),
        ));
        if has_actions {
            atoms.push_right(Atom::custom(
                actions_button_id,
                re_ui::Size::inherited(ui).icon_button_size(),
            ));
        }

        let right_padding = if has_actions {
            ACTIVE_ROW_RIGHT_PADDING
        } else {
            ROW_PADDING
        };
        let row = row_widget(ui, atoms, right_padding)
            .id(self.row_id)
            .allocate(ui);
        let row = paint_row(ui, row, self.is_active);

        if let Some(icon_rect) = row.rect(icon_id) {
            paint_blueprint_icon(ui, icon_rect, icon_tint, self.is_loading);
        }

        row.response.widget_info(|| {
            WidgetInfo::selected(egui::Role::Button, ui.is_enabled(), self.is_active, &label)
        });

        if let Some(button_rect) = row.rect(actions_button_id) {
            // The actions menu opens beside the dropdown, level with this row. It opens to the
            // right of the dropdown if it fits there, and otherwise to the left.
            let menu_anchor = row
                .response
                .rect
                .expand2(Vec2::new(f32::from(POPUP_PADDING), 0.0));
            let menu_id = actions.menu_id;
            // The active row is filled with the fill of `Variant::Opened`.
            let mut button_ui = ui.new_child(
                egui::UiBuilder::new()
                    .scope_id(self.row_id.with("actions_button"))
                    .max_rect(button_rect)
                    .layout(egui::Layout::right_to_left(egui::Align::Center))
                    .with_class(re_ui::theme::class::ON_OPENED),
            );
            button_ui.add(
                ui.small_icon_button_widget(&re_ui::icons::MORE, "Actions")
                    .on_hover_text("Actions")
                    .on_custom_menu(
                        move |popup| {
                            popup
                                .id(menu_id)
                                .style(menu_style())
                                .anchor(menu_anchor)
                                .align(RectAlign::RIGHT_START)
                                .align_alternatives(&[RectAlign::LEFT_START])
                                .gap(POPUP_GAP)
                        },
                        |ui| actions.menu_ui(ui),
                    ),
            );
        }

        let clicked = row.response.clicked();
        if clicked {
            ui.close();
        }

        clicked && !self.is_active
    }
}

/// What the actions menu of the active blueprint acts on.
struct BlueprintActions<'a, 'ctx> {
    store_context: &'a ActiveStoreContext<'ctx>,

    /// Why reverting the active blueprint would change nothing, if it wouldn't.
    revert_disabled_reason: Option<&'static str>,

    command_sender: &'a CommandSender,

    /// The id of the actions menu.
    menu_id: egui::Id,

    /// Set once a button in the actions menu sent its command, which then closes the dropdown.
    sent_command: Cell<bool>,
}

impl BlueprintActions<'_, '_> {
    fn menu_ui(&self, ui: &mut egui::Ui) {
        self.command_button_ui(
            ui,
            "Export .rbl…",
            RecordingCommandKind::SaveBlueprint,
            None,
        );

        ui.separator();

        let disabled_reason = self.revert_disabled_reason;
        let mut revert_text = RichText::new("Revert changes");
        if disabled_reason.is_none() {
            revert_text = revert_text.color(ui.tokens().error_fg_color);
        }
        self.command_button_ui(
            ui,
            revert_text,
            RecordingCommandKind::ResetBlueprint,
            disabled_reason,
        );
    }

    /// `kind` acting on the active recording.
    fn recording_command(&self, kind: RecordingCommandKind) -> RecordingCommand {
        RecordingCommand {
            recording_id: self.store_context.recording_store_id().clone(),
            kind,
        }
    }

    /// A menu button that runs `command` on the active recording.
    ///
    /// See [`RecordingCommand::button_ui`]. Clicking it closes the dropdown.
    fn command_button_ui(
        &self,
        ui: &mut egui::Ui,
        text: impl Into<egui::WidgetText>,
        command: RecordingCommandKind,
        disabled_reason: Option<&str>,
    ) {
        let response = self.recording_command(command).button_ui(
            ui,
            egui::Button::new(text),
            disabled_reason,
            self.command_sender,
        );

        if response.clicked() {
            self.sent_command.set(true);
            ui.close();
        }
    }
}
